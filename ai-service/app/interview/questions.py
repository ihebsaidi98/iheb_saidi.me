def get_question_by_id(question_id: str) -> dict | None:
    """Find a specific question by its unique question_id."""
    for q in QUESTION_BANK:
        if q["question_id"] == question_id:
            return q
    return None


def get_questions_for_session(track: str) -> list[dict]:
    """Return all 10 questions for a given track, ordered by difficulty (1–10).

    Returns 5 MCQ questions (difficulty 1–5) followed by 5 open-ended (difficulty 6–10).
    """
    track_questions = [q for q in QUESTION_BANK if q["track"] == track]
    return sorted(track_questions, key=lambda q: q["difficulty"])


def get_track_question_count(track: str) -> int:
    """Return the number of questions available for a given track."""
    return sum(1 for q in QUESTION_BANK if q["track"] == track)


def get_questions_by_track_and_difficulty(
    track: str,
    difficulty: str | None = None,
) -> list[dict]:
    """Retrieve questions for a track ordered by difficulty (1-10)."""
    return get_questions_for_session(track)
